import { chromium } from '@playwright/test'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1400, height: 1000 } })
p.on('requestfailed', r => console.log('FAILED', r.url(), r.failure()?.errorText))
p.on('response', async r => { if (r.url().includes('8097')||r.url().includes('/api/')) console.log('RES', r.status(), r.url(), (await r.text().catch(()=>'' )).slice(0,120)) })
p.on('console', m => { if (m.type()==='error') console.log('CONSOLE', m.text().slice(0,300)) })
await p.goto('http://127.0.0.1:3217/login', { waitUntil: 'networkidle' })
await p.waitForTimeout(1200)
await p.locator('input[type=email]').first().pressSequentially('grace@example.com', {delay:3})
await p.locator('input[type=password]').first().pressSequentially('password', {delay:3})
await p.getByRole('button', { name: /^Sign In$/ }).last().click()
await p.waitForTimeout(4000)
await p.goto('http://127.0.0.1:3217/programme/events', { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(6000)
await p.screenshot({ path: '/tmp/opencode/events2-364.png', fullPage: true })
await b.close()
