import { chromium } from '@playwright/test'
const b = await chromium.launch()
const p = await b.newPage({ viewport:{width:1400,height:1000} })
p.on('response', async r => { if (r.url().includes('8096')) console.log('RES', r.status(), r.url().replace('http://127.0.0.1:8096','')) })
p.on('console', m => { if (m.type()==='error') console.log('ERR', m.text().slice(0,250)) })
await p.goto('http://127.0.0.1:3217/login', {waitUntil:'networkidle'}); await p.waitForTimeout(2500)
const e=p.locator('input[type=email]').first(); await e.click(); await e.pressSequentially('grace@example.com',{delay:10})
const pw=p.locator('input[type=password]').first(); await pw.click(); await pw.pressSequentially('password',{delay:10})
await p.getByRole('button',{name:/^Sign In$/}).last().click(); await p.waitForTimeout(5000)
console.log('after login',p.url())
await p.goto('http://127.0.0.1:3217/programme/events/11111111-1111-4111-8111-111111111111',{waitUntil:'domcontentloaded'})
await p.waitForTimeout(9000)
console.log((await p.locator('body').innerText()).slice(0,900))
await p.screenshot({path:'/tmp/opencode/editor-364.png',fullPage:true})
await b.close()
